/// Width and height of each bitmap glyph in pixels.
pub const GLYPH_WIDTH: usize = 8;
pub const GLYPH_HEIGHT: usize = 8;

/// Atlas dimensions in glyphs.
pub const ATLAS_COLS: usize = 16;
pub const ATLAS_ROWS: usize = 6;

/// Total atlas dimensions in pixels (128 x 48).
pub const ATLAS_WIDTH: usize = ATLAS_COLS * GLYPH_WIDTH;
pub const ATLAS_HEIGHT: usize = ATLAS_ROWS * GLYPH_HEIGHT;

/// First printable ASCII character represented in the atlas (Space = 32).
pub const ASCII_START: u8 = 32;
/// Last printable ASCII character represented in the atlas ('~' = 126).
pub const ASCII_END: u8 = 126;

/// Maps any character to its atlas glyph index (0..95), falling back to '?' (31) for unsupported/non-ASCII characters (Amendment 5).
#[inline]
pub fn glyph_index_for_char(c: char) -> usize {
    if c.is_ascii() {
        let b = c as u8;
        if (ASCII_START..=ASCII_END).contains(&b) {
            return (b - ASCII_START) as usize;
        }
    }
    // Fallback: '?' is ASCII 63 -> index 63 - 32 = 31
    (b'?' - ASCII_START) as usize
}

/// Returns the UV bounding coordinates [u_min, v_min, u_max, v_max] in the atlas for a given character.
#[inline]
pub fn glyph_uv(c: char) -> [f32; 4] {
    let idx = glyph_index_for_char(c);
    let col = idx % ATLAS_COLS;
    let row = idx / ATLAS_COLS;

    let u_min = (col * GLYPH_WIDTH) as f32 / ATLAS_WIDTH as f32;
    let v_min = (row * GLYPH_HEIGHT) as f32 / ATLAS_HEIGHT as f32;
    let u_max = ((col + 1) * GLYPH_WIDTH) as f32 / ATLAS_WIDTH as f32;
    let v_max = ((row + 1) * GLYPH_HEIGHT) as f32 / ATLAS_HEIGHT as f32;

    [u_min, v_min, u_max, v_max]
}

