/// Generates a single-channel 8-bit grayscale pixel buffer (128x48 bytes) containing all 95 ASCII glyphs.
pub fn generate_font_atlas_pixels() -> Vec<u8> {
    let mut pixels = vec![0u8; ATLAS_WIDTH * ATLAS_HEIGHT];

    for (idx, glyph) in FONT_DATA.iter().enumerate() {
        let col = idx % ATLAS_COLS;
        let row = idx / ATLAS_COLS;
        let base_x = col * GLYPH_WIDTH;
        let base_y = row * GLYPH_HEIGHT;

        for (glyph_y, &byte_row) in glyph.iter().enumerate() {
            for glyph_x in 0..GLYPH_WIDTH {
                let bit = (byte_row >> (7 - glyph_x)) & 1;
                let pixel_val = if bit == 1 { 255u8 } else { 0u8 };
                let target_x = base_x + glyph_x;
                let target_y = base_y + glyph_y;
                let offset = target_y * ATLAS_WIDTH + target_x;
                pixels[offset] = pixel_val;
            }
        }
    }

    pixels
}
